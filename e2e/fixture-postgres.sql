CREATE VIEW v_customer_orders AS SELECT c.name, COUNT(o.id) AS n FROM customer c LEFT JOIN orders o ON o.customer_id = c.id GROUP BY c.name;
CREATE PROCEDURE add_customer(p_name varchar)
LANGUAGE plpgsql
AS $$
BEGIN
  INSERT INTO shop.customer (name) VALUES (p_name);
END
$$;
CREATE FUNCTION customer_count() RETURNS integer
LANGUAGE plpgsql STABLE
AS $$
BEGIN
  RETURN (SELECT COUNT(*) FROM shop.customer);
END
$$;
CREATE FUNCTION customer_trim_name() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.name := trim(NEW.name);
  RETURN NEW;
END
$$;
CREATE TRIGGER customer_bi BEFORE INSERT ON customer FOR EACH ROW EXECUTE FUNCTION customer_trim_name();
CREATE SEQUENCE dbm_seq;
CREATE TYPE dbm_mood AS ENUM ('sad', 'ok', 'happy');
