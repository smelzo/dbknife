// PostgreSQL inspector pages from pg_catalog and the statistics views.

/** pg_class c and pg_namespace n of the relation $1.$2. */
const relation = 'pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = $1 AND c.relname = $2'

const relkind = `CASE c.relkind WHEN 'r' THEN 'BASE TABLE' WHEN 'p' THEN 'PARTITIONED TABLE' WHEN 'f' THEN 'FOREIGN TABLE'
  WHEN 'v' THEN 'VIEW' WHEN 'm' THEN 'MATERIALIZED VIEW' END`

/** Referential action of pg_constraint.confupdtype / confdeltype. */
const action = (column: string): string =>
  `CASE ${column} WHEN 'a' THEN 'NO ACTION' WHEN 'r' THEN 'RESTRICT' WHEN 'c' THEN 'CASCADE' WHEN 'n' THEN 'SET NULL' WHEN 'd' THEN 'SET DEFAULT' END`

// tgtype bits (pg_trigger.h): 2 BEFORE, 64 INSTEAD; 4 INSERT, 8 DELETE, 16 UPDATE, 32 TRUNCATE
const triggerTiming = `CASE WHEN t.tgtype & 2 <> 0 THEN 'BEFORE' WHEN t.tgtype & 64 <> 0 THEN 'INSTEAD OF' ELSE 'AFTER' END`
const triggerEvent = `concat_ws(' OR ', CASE WHEN t.tgtype & 4 <> 0 THEN 'INSERT' END, CASE WHEN t.tgtype & 16 <> 0 THEN 'UPDATE' END,
  CASE WHEN t.tgtype & 8 <> 0 THEN 'DELETE' END, CASE WHEN t.tgtype & 32 <> 0 THEN 'TRUNCATE' END)`
const triggerEnabled = `CASE t.tgenabled WHEN 'D' THEN 'DISABLED' WHEN 'R' THEN 'REPLICA' WHEN 'A' THEN 'ALWAYS' ELSE 'ENABLED' END`

