CREATE TABLE `parted` (
  `id` int(11) NOT NULL,
  `yr` int(11) NOT NULL,
  PRIMARY KEY (`id`,`yr`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1 COLLATE=latin1_swedish_ci
 PARTITION BY RANGE (`yr`)
(PARTITION `p0` VALUES LESS THAN (2000) ENGINE = InnoDB,
 PARTITION `p1` VALUES LESS THAN MAXVALUE ENGINE = InnoDB)